package main

import "fmt"

func main() {
	var name string = "Luis"
	fmt.Printf("Hola, %s\n", name)

	var enterto int = 4
	var entero1, entero2 int = 10, 20

	fmt.Println(enterto, entero1, entero2)

	var booleano bool = true
	fmt.Println(booleano)

	var enteroSimple int
	fmt.Println(enteroSimple)
	enteroSimple = 5
	fmt.Println(enteroSimple)

	fruta := "Manzana" // declara una variable de tipo string
	fmt.Println(fruta)
}
